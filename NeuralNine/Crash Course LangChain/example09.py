from langchain.messages import HumanMessage, SystemMessage
from langchain_ollama import ChatOllama
from langchain.agents import create_agent
from langchain.agents.middleware import ModelRequest, ModelResponse, wrap_model_call
# from langchain.chat_models import init_chat_model


# ============================================================
# 1. MODEL CONFIGURATION
# ============================================================

# Small and fast model used for simple conversations.
BASIC_MODEL = "qwen3.5:0.8b"

# Larger and more capable model used for more complex or longer conversations.
ADVANCED_MODEL = "qwen3.5:9b"


# ============================================================
# 2. INITIALIZE THE LANGUAGE MODELS
# ============================================================

# Initialize the basic model using Ollama.
basic_model = ChatOllama(model=BASIC_MODEL, temperature=0)

# Initialize the advanced model using Ollama.
advanced_model = ChatOllama(model=ADVANCED_MODEL, temperature=0)


# ============================================================
# 3. ALTERNATIVE MODEL CONFIGURATION
